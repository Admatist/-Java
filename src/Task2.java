public class Task2 {
    public static void main(String[] args) {
        double num1 = 15.5;
        double num2 = 5.0;

        double sum = num1 + num2;      // Сложение
        double product = num1 * num2;  // Умножение
        double quotient = num1 / num2; // Деление

        System.out.println("Число 1: " + num1 + ", Число 2: " + num2);
        System.out.println("Результат сложения: " + sum);
        System.out.println("Результат умножения: " + product);
        System.out.println("Результат деления: " + quotient);
    }
}